static void border_collision(vec3s *a, vec2s size, vec2s start, vec2s end) {
    if (a->y < start.y) a->y = start.y;
    if (a->x < start.x) a->x = start.x;

    if (a->x + size.x > end.x) a->x = end.x - size.x;
    if (a->y + size.y > end.y) a->y = end.y - size.y;
}

